// Pointer variable pointing to s_bionic_ctype[0]
static const uint8_t* s_bionic_ctype_ptr = &s_bionic_ctype[0];

// Standard I/O dummy stream buffers
alignas(16) static uint8_t s_bionic_sF[3 * 128] = {0};
static void* s_bionic_stdin_ptr = &s_bionic_sF[0];
static void* s_bionic_stdout_ptr = &s_bionic_sF[128];
static void* s_bionic_stderr_ptr = &s_bionic_sF[256];

void init_bionic_libc() {
    std::memset(s_bionic_sF, 0, sizeof(s_bionic_sF));
    std::cout << "[Bionic libc init] &sF[0]=" << (void*)&s_bionic_sF[0]
              << " &sF[256]=" << (void*)&s_bionic_sF[256]
              << " &stderr_ptr=" << (void*)&s_bionic_stderr_ptr << "\n";
}

uint64_t resolve_bionic_libc_data(std::string_view name) {
    if (name == "_ctype_") {
        return reinterpret_cast<uint64_t>(&s_bionic_ctype_ptr);
    }
    if (name == "__sF") {
        return reinterpret_cast<uint64_t>(&s_bionic_sF[0]);
    }
    if (name == "stdout") {
        return reinterpret_cast<uint64_t>(&s_bionic_stdout_ptr);
    }
    if (name == "stderr") {
        return reinterpret_cast<uint64_t>(&s_bionic_stderr_ptr);
    }
    if (name == "stdin") {
        return reinterpret_cast<uint64_t>(&s_bionic_stdin_ptr);
    }
    return 0;
}

FILE* translate_guest_file_ptr(uint64_t guest_fp) {
    if (guest_fp == 0) return nullptr;
    uint64_t sF_base = reinterpret_cast<uint64_t>(&s_bionic_sF[0]);
    if (guest_fp >= sF_base && guest_fp < sF_base + sizeof(s_bionic_sF)) {
        size_t off = guest_fp - sF_base;
        if (off < 128) return stdin;
        if (off < 256) return stdout;
        return stderr;
    }
    if (guest_fp == reinterpret_cast<uint64_t>(&s_bionic_stdout_ptr) ||
        guest_fp == reinterpret_cast<uint64_t>(s_bionic_stdout_ptr)) {
        return stdout;
    }
    if (guest_fp == reinterpret_cast<uint64_t>(&s_bionic_stderr_ptr) ||
        guest_fp == reinterpret_cast<uint64_t>(s_bionic_stderr_ptr)) {
        return stderr;
    }
    if (guest_fp == reinterpret_cast<uint64_t>(&s_bionic_stdin_ptr) ||
        guest_fp == reinterpret_cast<uint64_t>(s_bionic_stdin_ptr)) {
        return stdin;
    }
    return reinterpret_cast<FILE*>(guest_fp);
}

